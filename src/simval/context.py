def register_engine(adapter: EngineAdapter) -> None:
    _ENGINES.append(adapter)


def select_engine(run: Path) -> EngineAdapter:
    """Evaluate EVERY detector and require exactly one match (audit ENG-001).

    First-match selection made detection order load-bearing: the synthetic
    engine (registered early, loosely keyed on *.npy) silently swallowed
    run-dirs of concrete domains that carried a stray npy file, skipping
    their domain checks and provenance. Ambiguity now fails closed, naming
    the candidates."""
    _load_optional_engines()
    matches = [eng for eng in _ENGINES if eng.detect(run)]
    if len(matches) == 1:
        return matches[0]
    names = sorted(eng.name for eng in matches)
    if not matches:
        raise ValueError(f"no engine recognized run-dir: {run}")
    raise ValueError(
        f"ambiguous run-dir {run}: engines {names} all match — a run-dir must "
        "identify exactly one domain (audit ENG-001)"
    )
